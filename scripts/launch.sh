#!/bin/bash
#
# launch.sh - build, trace, co-locate and evaluate a kryptos attack.
#
# Usage:
#   source scripts/set_env.sh
#   ./scripts/launch.sh <attack_name>
#
# Expects an attack directory codes/<attack_name>/ containing:
#   config.h          shared #defines (champsim/cache params) for victim + attacker
#   victim.c          the victim workload (runs on core 0)
#   attacker.c        the attacker workload (runs on core 1)
#   pythia_config.ini the Pythia prefetcher knobs to evaluate against
#   rollup.py         per-attack result analysis
#
# What it does:
#   1. compiles + traces victim.c and attacker.c (and a shared idle baseline),
#      generating traces only when they are missing.
#   2. writes experiments/<attack_name>/{.tlist,.exp,.mfile}.
#   3. fans out ChampSim runs over Slurm (co-located pairs x prefetcher configs).
#   4. waits for all jobs, then runs the attack's rollup.py.
#
# Tunable via env (all optional):
#   TRACE_INSTR   instructions to trace per workload   (default 50000000)
#   WARMUP        champsim warmup instructions         (default 10000000)
#   SIM           champsim simulation instructions     (default 40000000)
#   PARTITION     slurm partition                      (default debug)
#   NCORES        cpus per slurm job                   (default 2)

set -u

if [[ -z "${KRYPTOS_ENV:-}" ]]; then
    echo "Env variables not set. Source scripts/set_env.sh before running this script!" >&2
    exit 1
fi

if [[ $# -ne 1 ]]; then
    echo "Usage: $0 <attack_name>" >&2
    exit 1
fi

ATTACK="$1"
ATTACK_DIR="$CODES_DIR/$ATTACK"

TRACE_INSTR="${TRACE_INSTR:-50000000}"
WARMUP="${WARMUP:-10000000}"
SIM="${SIM:-40000000}"
PARTITION="${PARTITION:-debug}"
NCORES="${NCORES:-2}"

GEN_TRACE="$SCRIPTS_DIR/gen_trace.sh"
IDLE_SRC="$CODES_DIR/_common/idle.c"

# ---------------------------------------------------------------------------
# 1. validate inputs
# ---------------------------------------------------------------------------
if [[ ! -d "$ATTACK_DIR" ]]; then
    echo "[ERROR] Attack '$ATTACK' not found at $ATTACK_DIR" >&2
    exit 1
fi

# An attack may ship a 'matrix' manifest declaring its own neighbor/config grid
# (see codes/degree_bw/matrix). Without one, fall back to the default layout:
# victim + {attacker, idle} x {nopref, pythia}.
MATRIX="$ATTACK_DIR/matrix"
MANIFEST_MODE=0
[[ -f "$MATRIX" ]] && MANIFEST_MODE=1

if [[ $MANIFEST_MODE -eq 1 ]]; then
    REQUIRED=(config.h victim.c rollup.py matrix)
else
    REQUIRED=(config.h victim.c attacker.c pythia_config.ini rollup.py)
fi
for f in "${REQUIRED[@]}"; do
    if [[ ! -f "$ATTACK_DIR/$f" ]]; then
        echo "[ERROR] Missing $f in $ATTACK_DIR" >&2
        exit 1
    fi
done

if [[ ! -x "$EXE" ]]; then
    echo "[ERROR] 2-core ChampSim binary not found/executable: $EXE" >&2
    echo "        Build it, e.g.: ./build_champsim.sh bop scooby no 2" >&2
    exit 1
fi

# Resolve a manifest <source> to a path: attack dir first, then codes/.
resolve_src() {
    if [[ -f "$ATTACK_DIR/$1" ]]; then echo "$ATTACK_DIR/$1";
    elif [[ -f "$CODES_DIR/$1" ]]; then echo "$CODES_DIR/$1";
    else echo ""; fi
}

EXP_DIR="$EXP_ROOT/$ATTACK"
mkdir -p "$EXP_DIR"

TLIST="$EXP_DIR/$ATTACK.tlist"
EXP="$EXP_DIR/$ATTACK.exp"
MFILE="$EXP_DIR/$ATTACK.mfile"
JOBFILE="$EXP_DIR/jobfile.sh"

# Metrics to roll up: per-core IPC (manifest attacks parse more in rollup.py).
cat > "$MFILE" <<EOF
Core_0_IPC : sum
Core_1_IPC : sum
EOF

if [[ $MANIFEST_MODE -eq 1 ]]; then
    # -----------------------------------------------------------------------
    # 2m/3m. manifest-driven matrix: trace victim + each neighbor (with args),
    #        build one tlist block per neighbor and one exp line per config.
    # -----------------------------------------------------------------------
    echo "=== Manifest matrix for '$ATTACK' ($MATRIX) ==="

    : > "$TLIST"
    {
        echo "# Auto-generated by launch.sh for attack '$ATTACK' (manifest)"
        echo "BASE = --warmup_instructions=${WARMUP} --simulation_instructions=${SIM}"
    } > "$EXP"

    # A matrix may declare ONE victim (legacy: tlist block named <neighbor>) or
    # SEVERAL named victims (sweep: block named <victim>_<neighbor>, so every
    # victim is crossed with every neighbor x config). Count victim lines to pick
    # the path; the single-victim path is byte-for-byte the original behaviour.
    NVICTIM=$(grep -cE '^[[:space:]]*victim[[:space:]]' "$MATRIX")

    victim_done=0
    if [[ $NVICTIM -gt 1 ]]; then
        # ------- multi-victim sweep: victim <name> <source> [args...] ---------
        declare -a VIC_NAMES VIC_TRACES
        declare -a NB_NAMES NB_TRACES
        while IFS= read -r line || [[ -n "$line" ]]; do
            line="${line%%#*}"
            [[ -z "${line// }" ]] && continue
            read -ra F <<< "$line"
            kind="${F[0]}"
            case "$kind" in
            victim)
                name="${F[1]}"
                src="$(resolve_src "${F[2]}")"
                [[ -z "$src" ]] && { echo "[ERROR] victim '$name' source '${F[2]}' not found" >&2; exit 1; }
                args="${F[*]:3}"
                vtrace="${ATTACK}_${name}"
                "$GEN_TRACE" "$src" "$vtrace" "$TRACE_INSTR" "$ATTACK_DIR" "$args" || exit 1
                VIC_NAMES+=("$name"); VIC_TRACES+=("$vtrace")
                ;;
            neighbor)
                name="${F[1]}"
                src="$(resolve_src "${F[2]}")"
                [[ -z "$src" ]] && { echo "[ERROR] neighbor '$name' source '${F[2]}' not found" >&2; exit 1; }
                args="${F[*]:3}"
                nbtrace="${ATTACK}_${name}"
                "$GEN_TRACE" "$src" "$nbtrace" "$TRACE_INSTR" "$ATTACK_DIR" "$args" || exit 1
                NB_NAMES+=("$name"); NB_TRACES+=("$nbtrace")
                ;;
            config)
                cname="${F[1]}"
                ini="$ATTACK_DIR/${F[2]}"
                [[ -f "$ini" ]] || { echo "[ERROR] config '$cname' ini not found: $ini" >&2; exit 1; }
                echo "${cname}	\$(BASE) --l2c_prefetcher_types=scooby --config=${ini}" >> "$EXP"
                ;;
            *)
                echo "[WARN] ignoring unknown matrix line: $line" >&2
                ;;
            esac
        done < "$MATRIX"

        [[ ${#NB_NAMES[@]} -gt 0 ]] || { echo "[ERROR] matrix defines no 'neighbor' line" >&2; exit 1; }
        # cross every victim with every neighbor -> one tlist block each
        for vi in "${!VIC_NAMES[@]}"; do
            for nj in "${!NB_NAMES[@]}"; do
                {
                    echo "NAME=${VIC_NAMES[$vi]}_${NB_NAMES[$nj]}"
                    echo "TRACE=\$(PYTHIA_HOME)/traces/${VIC_TRACES[$vi]}.champsimtrace.xz \$(PYTHIA_HOME)/traces/${NB_TRACES[$nj]}.champsimtrace.xz"
                    echo "KNOBS="
                    echo ""
                } >> "$TLIST"
            done
        done
        victim_done=1
    else
        # ------- single victim (legacy): tlist block named <neighbor> ---------
        VICTIM_TRACE="${ATTACK}_victim"
        while IFS= read -r line || [[ -n "$line" ]]; do
            line="${line%%#*}"                               # strip comments
            [[ -z "${line// }" ]] && continue                # skip blanks
            read -ra F <<< "$line"
            kind="${F[0]}"

            case "$kind" in
            victim)
                src="$(resolve_src "${F[1]}")"
                [[ -z "$src" ]] && { echo "[ERROR] victim source '${F[1]}' not found" >&2; exit 1; }
                args="${F[*]:2}"
                "$GEN_TRACE" "$src" "$VICTIM_TRACE" "$TRACE_INSTR" "$ATTACK_DIR" "$args" || exit 1
                victim_done=1
                ;;
            neighbor)
                name="${F[1]}"
                src="$(resolve_src "${F[2]}")"
                [[ -z "$src" ]] && { echo "[ERROR] neighbor '$name' source '${F[2]}' not found" >&2; exit 1; }
                args="${F[*]:3}"
                nb_trace="${ATTACK}_${name}"
                "$GEN_TRACE" "$src" "$nb_trace" "$TRACE_INSTR" "$ATTACK_DIR" "$args" || exit 1
                {
                    echo "NAME=${name}"
                    echo "TRACE=\$(PYTHIA_HOME)/traces/${VICTIM_TRACE}.champsimtrace.xz \$(PYTHIA_HOME)/traces/${nb_trace}.champsimtrace.xz"
                    echo "KNOBS="
                    echo ""
                } >> "$TLIST"
                ;;
            config)
                cname="${F[1]}"
                ini="$ATTACK_DIR/${F[2]}"
                [[ -f "$ini" ]] || { echo "[ERROR] config '$cname' ini not found: $ini" >&2; exit 1; }
                echo "${cname}	\$(BASE) --l2c_prefetcher_types=scooby --config=${ini}" >> "$EXP"
                ;;
            *)
                echo "[WARN] ignoring unknown matrix line: $line" >&2
                ;;
            esac
        done < "$MATRIX"
    fi

    [[ $victim_done -eq 1 ]] || { echo "[ERROR] matrix defines no 'victim' line" >&2; exit 1; }
else
    # -----------------------------------------------------------------------
    # 2. generate traces (only if missing)
    # -----------------------------------------------------------------------
    if [[ ! -f "$IDLE_SRC" ]]; then
        echo "[ERROR] Shared idle baseline missing: $IDLE_SRC" >&2
        exit 1
    fi
    echo "=== Generating traces for '$ATTACK' (if needed) ==="

    VICTIM_TRACE="${ATTACK}_victim"
    ATTACKER_TRACE="${ATTACK}_attacker"
    IDLE_TRACE="idle"

    "$GEN_TRACE" "$ATTACK_DIR/victim.c"   "$VICTIM_TRACE"   "$TRACE_INSTR" "$ATTACK_DIR" || exit 1
    "$GEN_TRACE" "$ATTACK_DIR/attacker.c" "$ATTACKER_TRACE" "$TRACE_INSTR" "$ATTACK_DIR" || exit 1
    "$GEN_TRACE" "$IDLE_SRC"              "$IDLE_TRACE"     "$TRACE_INSTR" "$ATTACK_DIR" || exit 1

    # ----------------------------------------------------------------------
    # 3. build the experiment (tlist / exp)
    # ----------------------------------------------------------------------
    # Co-located pairs: victim(core 0) + {attacker, idle}(core 1).
    cat > "$TLIST" <<EOF
NAME=${ATTACK}_attack
TRACE=\$(PYTHIA_HOME)/traces/${VICTIM_TRACE}.champsimtrace.xz \$(PYTHIA_HOME)/traces/${ATTACKER_TRACE}.champsimtrace.xz
KNOBS=

NAME=${ATTACK}_idle
TRACE=\$(PYTHIA_HOME)/traces/${VICTIM_TRACE}.champsimtrace.xz \$(PYTHIA_HOME)/traces/${IDLE_TRACE}.champsimtrace.xz
KNOBS=
EOF

    # Prefetcher configs: no prefetcher baseline + Pythia with this attack's ini.
    cat > "$EXP" <<EOF
# Auto-generated by launch.sh for attack '$ATTACK'
BASE = --warmup_instructions=${WARMUP} --simulation_instructions=${SIM}
NOPREF = --config=\$(PYTHIA_HOME)/config/nopref.ini
PYTHIA = --l2c_prefetcher_types=scooby --config=${ATTACK_DIR}/pythia_config.ini

nopref		\$(BASE) \$(NOPREF)
pythia		\$(BASE) \$(PYTHIA)
EOF
fi

echo "=== Experiment files written to $EXP_DIR ==="

# ---------------------------------------------------------------------------
# 4. generate jobfile (slurm or local) and run
# ---------------------------------------------------------------------------
# LOCAL=1 => run each sim directly in this shell instead of fanning out over
# Slurm (opt-in escape hatch for machines without Slurm). Each jobfile line
# already redirects to <neighbor>_<cfg>.out, so we execute them in the exp dir.
# Default is Slurm; if the controller is down we fail loudly rather than switch.
LOCAL="${LOCAL:-0}"

perl "$SCRIPTS_DIR/create_jobfile.pl" \
    --exe "$EXE" \
    --tlist "$TLIST" --exp "$EXP" \
    --local "$LOCAL" --partition "$PARTITION" --ncores "$NCORES" \
    > "$JOBFILE"

chmod +x "$JOBFILE"
cd "$EXP_DIR" || exit 1

if [[ "$LOCAL" == "1" ]]; then
    # -----------------------------------------------------------------------
    # 5-local. run each sim sequentially in this shell.
    # -----------------------------------------------------------------------
    echo "=== Running '$ATTACK' jobs locally (no Slurm) ==="
    njobs=0 nfail=0
    while IFS= read -r line || [[ -n "$line" ]]; do
        [[ -z "$line" || "$line" =~ ^[[:space:]]*# ]] && continue
        njobs=$((njobs + 1))
        outname=$(echo "$line" | grep -oE '> [^ ]+\.out' | awk '{print $2}')
        echo "[RUN $njobs] ${outname:-job}"
        if ! bash -c "$line"; then
            echo "[ERROR] local run failed: ${outname:-$line}" >&2
            nfail=$((nfail + 1))
        fi
    done < "$JOBFILE"
    echo "=== Local runs done: $njobs run, $nfail failed. Running rollup. ==="
else

# ---------------------------------------------------------------------------
# 5. submit + monitor slurm jobs
# ---------------------------------------------------------------------------
declare -A active_jobs

echo "=== Submitting Slurm jobs for '$ATTACK' ==="
while IFS= read -r line || [[ -n "$line" ]]; do
    [[ -z "$line" || "$line" =~ ^[[:space:]]*# ]] && continue

    job_name="unknown"
    if [[ "$line" =~ -J[[:space:]]+([^[:space:]]+) ]]; then
        job_name="${BASH_REMATCH[1]}"
    fi

    raw_out=$(eval "$line --parsable" 2>&1)
    status=$?
    if [[ $status -ne 0 ]]; then
        echo "[ERROR] Submission failed for $job_name: $raw_out"
        continue
    fi

    job_id=$(echo "$raw_out" | tail -n 1 | cut -d';' -f1 | grep -oE '[0-9]+')
    if [[ -z "$job_id" ]]; then
        echo "[ERROR] Failed to extract numeric Job ID from: $raw_out"
        continue
    fi

    active_jobs["$job_id"]="$job_name"
    echo "[SUBMITTED] $job_name -> ID: $job_id"
done < "$JOBFILE"

total_jobs=${#active_jobs[@]}
if [[ $total_jobs -eq 0 ]]; then
    echo "[ERROR] No jobs submitted. Check Slurm / jobfile." >&2
    exit 1
fi
echo "Submitted $total_jobs jobs. Monitoring..."

while [[ ${#active_jobs[@]} -gt 0 ]]; do
    sleep 5
    for jid in "${!active_jobs[@]}"; do
        state=$(squeue -j "$jid" -h -o "%T" 2>/dev/null)
        if [[ -z "$state" ]]; then
            final_status=$(sacct -j "$jid" -X -n -o "State" 2>/dev/null | tr -d ' ')
            [[ -z "$final_status" ]] && final_status="DONE"
            echo "[FINISHED] ID: $jid (${active_jobs[$jid]}) -> $final_status"
            unset "active_jobs[$jid]"
        fi
    done
done

echo "=== All jobs done. Running rollup. ==="
fi

# ---------------------------------------------------------------------------
# 6. per-attack analysis
# ---------------------------------------------------------------------------
if [[ $MANIFEST_MODE -eq 1 ]]; then
    python3 "$ATTACK_DIR/rollup.py" --exp-dir "$EXP_DIR" --attack "$ATTACK" \
        --manifest "$MATRIX" --csv "$EXP_DIR/rollup.csv" \
        --plot "$EXP_DIR/degree_dist.png" \
        | tee "$EXP_DIR/rollup.txt"
else
    python3 "$ATTACK_DIR/rollup.py" --exp-dir "$EXP_DIR" --attack "$ATTACK" \
        | tee "$EXP_DIR/rollup.txt"
fi

echo "=== Done. Results in $EXP_DIR ==="
